def ptext(p):
    return ''.join(t.text or '' for t in p.iter(q('t')))


def set_para(p, text):
    runs = p.findall(q('r'))
    if not runs:
        raise RuntimeError('段落無 run：' + ptext(p)[:40])
    first = runs[0]
    ts = first.findall(q('t'))
    if not ts:
        ts = [etree.SubElement(first, q('t'))]
    ts[0].text = text
    ts[0].set('{http://www.w3.org/XML/1998/namespace}space', 'preserve')
    for extra in ts[1:]:
        first.remove(extra)
    for r in runs[1:]:
        p.remove(r)


def set_cell(tc, text):
    ps = tc.findall(q('p'))
    for p in ps[1:]:
        tc.remove(p)
    p = ps[0]
    if not p.findall(q('r')):
        r = etree.SubElement(p, q('r'))
        etree.SubElement(r, q('t'))
    set_para(p, text)


def fill(tbl, start_row, data, label):
    rs = tbl.findall(q('tr'))
    assert len(rs) - start_row == len(data), '%s 列數不符 %d vs %d' % (label, len(rs) - start_row, len(data))
    for i, vals in enumerate(data):
        cs = rs[start_row + i].findall(q('tc'))
        assert len(cs) == len(vals), '%s 第%d列欄數不符 %d vs %d' % (label, i, len(cs), len(vals))
        for c, v in zip(cs, vals):
            set_cell(c, v)


