def main():
    with zipfile.ZipFile(DOC) as z:
        xml = z.read('word/document.xml')
    root = etree.fromstring(xml)
    body = root.find(q('body'))
    els = list(body)

    def chk(i, expect):
        t = ptext(els[i])
        assert expect in t, '索引 %d 內容不符：%s' % (i, t[:60])

    chk(358, '表2-14、103~113年嘉義縣作物收穫面積與產量統計表')
    chk(361, '表2-15、113年嘉義縣各鄉鎮作物收穫面積與產量統計表')
    chk(356, '嘉義縣稻作收穫面積自103年')
    chk(357, '113年稻米生產重鎮為新港鄉與民雄鄉')
    chk(138, '表2-14、103~113年')
    chk(139, '表2-15、113年')

    fill(els[359], 2, T214, '表2-14')
    fill(els[362], 2, T215, '表2-15')

    set_para(els[358], '表2-14、104~114年嘉義縣作物收穫面積與產量統計表')
    set_para(els[361], '表2-15、114年嘉義縣各鄉鎮作物收穫面積與產量統計表')
    set_para(els[360], SRC_NOTE)
    set_para(els[363], SRC_NOTE)
    set_para(els[356], P356)
    set_para(els[357], P357)

    # 表目錄（功能變數，只換 w:t 內字串）
    for i, old, new in ((138, '103~113', '104~114'), (139, '113', '114')):
        done = False
        for t in els[i].iter(q('t')):
            if t.text and old in t.text:
                t.text = t.text.replace(old, new, 1); done = True; break
        print('TOC[%d] %s -> %s' % (i, done, ptext(els[i])[:40]))

    newxml = etree.tostring(root, xml_declaration=True, encoding='UTF-8', standalone=True)

    bak = DOC.replace('.docx', '_備份%s.docx' % datetime.datetime.now().strftime('%H%M%S'))
    shutil.copy2(DOC, bak)
    tmp = DOC + '.tmp'
    with zipfile.ZipFile(DOC) as zin, zipfile.ZipFile(tmp, 'w', zipfile.ZIP_DEFLATED) as zout:
        for item in zin.infolist():
            data = zin.read(item.filename)
            if item.filename == 'word/document.xml':
                data = newxml
            zi = zipfile.ZipInfo(item.filename, date_time=item.date_time)
            zi.compress_type = item.compress_type
            zi.external_attr = item.external_attr
            zout.writestr(zi, data)
    os.replace(tmp, DOC)
    print('備份：', bak)
    print('已更新：', DOC, os.path.getsize(DOC))


if __name__ == '__main__':
    main()
